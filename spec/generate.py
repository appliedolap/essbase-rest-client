def render_pair_html(diff: dict, links) -> str:
    old_version, new_version = diff["old"], diff["new"]
    operations, models = diff["operations"], diff["models"]

    old_ops = len(spec.operations_of(diff["old_spec"]))
    new_ops = len(spec.operations_of(diff["new_spec"]))
    old_models = len(spec.schemas_of(diff["old_spec"]))
    new_models = len(spec.schemas_of(diff["new_spec"]))

    body = [
        f"<h2>Essbase {esc(old_version)} &rarr; {esc(new_version)}</h2>",
        '<p class="lede">Description and summary text changes are ignored; everything '
        "below is a change to the shape of the API.</p>",
        '<div class="scroll"><table><thead><tr><th></th>'
        f"<th class=\"num\">{esc(old_version)}</th><th class=\"num\">{esc(new_version)}</th>"
        '<th class="num">Change</th></tr></thead><tbody>'
        f'<tr><td>Endpoints</td><td class="num">{old_ops}</td>'
        f'<td class="num">{new_ops}</td><td class="num">{new_ops - old_ops:+d}</td></tr>'
        f'<tr><td>Models</td><td class="num">{old_models}</td>'
        f'<td class="num">{new_models}</td><td class="num">{new_models - old_models:+d}</td></tr>'
        "</tbody></table></div>",
        f"<h2>Endpoints added in {esc(new_version)}</h2>",
        endpoint_list_html(operations["added"], "No new endpoints."),
        f"<h2>Endpoints removed in {esc(new_version)}</h2>",
        endpoint_list_html(operations["removed"], "No endpoints removed."),
        "<h2>Endpoints changed</h2>",
    ]

    if operations["changed"]:
        items = "".join(
            f'<li><span class="verb {esc(method)}">{esc(method)}</span>'
            f"<code>{esc(path)}</code><ul>"
            + "".join(f"<li class=\"summary\">{esc(note)}</li>" for note in notes)
            + "</ul></li>"
            for (method, path), notes in operations["changed"]
        )
        body.append(f'<ul class="endpoints">{items}</ul>')
    else:
        body.append('<p class="note">None.</p>')

    for title, key in (("Models added", "added"), ("Models removed", "removed")):
        body.append(f"<h2>{title} in {esc(new_version)}</h2>")
        if models[key]:
            body.append(
                '<ul class="endpoints">'
                + "".join(
                    f"<li><code>{esc(name)}</code> "
                    f'<span class="summary">{count} properties</span></li>'
                    for name, count in models[key]
                )
                + "</ul>"
            )
        else:
            body.append('<p class="note">None.</p>')

    body.append("<h2>Models changed</h2>")
    if models["changed"]:
        items = "".join(
            f"<li><code>{esc(name)}</code><ul>"
            + "".join(f'<li class="summary">{esc(note)}</li>' for note in notes)
            + "</ul></li>"
            for name, notes in models["changed"]
        )
        body.append(f'<ul class="endpoints">{items}</ul>')
    else:
        body.append('<p class="note">None.</p>')

    return page(
        f"Essbase {old_version} to {new_version}",
        f"{old_version}-{new_version}",
        "\n".join(body),
        links,
    )


