def esc(text: str) -> str:
    return html.escape(str(text), quote=True)


def page(title: str, active: str, body: str, links: list[tuple[str, str, str]]) -> str:
    nav = "".join(
        '<a href="{href}"{on}>{label}</a>'.format(
            href=esc(href),
            on=' class="on"' if key == active else "",
            label=esc(label),
        )
        for key, href, label in links
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<style>{CSS}</style>
</head>
<body>
<header><div class="inner">
<h1>Essbase REST Java Client</h1>
<nav>{nav}</nav>
</div></header>
<main>
{body}
<footer>
Generated by <code>spec/generate.py</code> from the specifications archived in
<code>spec/versions/</code>.
<a href="https://github.com/appliedolap/essbase-rest-client">Source on GitHub</a>.
</footer>
</main>
</body>
</html>
"""


def nav_links(diffs: list[dict]) -> list[tuple[str, str, str]]:
    links = [("index", "index.html", "What's new"), ("coverage", "coverage.html", "Coverage")]
    links.extend(
        (f"{diff['old']}-{diff['new']}", f"{diff['old']}-to-{diff['new']}.html",
         f"{diff['old']} → {diff['new']}")
        for diff in diffs
    )
    links.append(("api", "api/index.html", "Javadoc"))
    return links


def endpoint_list_html(entries: list[tuple[spec.Endpoint, str]], empty: str = "None.") -> str:
    if not entries:
        return f'<p class="note">{esc(empty)}</p>'
    items = "".join(
        f'<li><span class="verb {esc(method)}">{esc(method)}</span>'
        f'<code>{esc(path)}</code>'
        + (f'<div class="summary">{esc(summary)}</div>' if summary else "")
        + "</li>"
        for (method, path), summary in entries
    )
    return f'<ul class="endpoints">{items}</ul>'


