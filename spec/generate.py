def endpoint_line(key: spec.Endpoint, summary: str) -> str:
    method, path = key
    line = f"- `{method}` `{path}`"
    return f"{line} - {summary}" if summary else line


def render_pair_markdown(diff: dict) -> str:
    old_version, new_version = diff["old"], diff["new"]
    operations, models = diff["operations"], diff["models"]

    old_ops = len(spec.operations_of(diff["old_spec"]))
    new_ops = len(spec.operations_of(diff["new_spec"]))
    old_models = len(spec.schemas_of(diff["old_spec"]))
    new_models = len(spec.schemas_of(diff["new_spec"]))

    lines = [
        f"# Essbase REST API: {old_version} to {new_version}",
        "",
        "Generated by `spec/generate.py`. Description and summary text changes are",
        "ignored; everything below is a change to the shape of the API.",
        "",
        f"| | {old_version} | {new_version} | Change |",
        "| --- | ---: | ---: | ---: |",
        f"| Endpoints | {old_ops} | {new_ops} | {new_ops - old_ops:+d} |",
        f"| Models | {old_models} | {new_models} | {new_models - old_models:+d} |",
        "",
    ]

    def section(title: str, body: list[str]) -> None:
        lines.extend([f"## {title}", ""])
        lines.extend(body if body else ["_None._"])
        lines.append("")

    section(
        f"Endpoints added in {new_version}",
        [endpoint_line(key, summary) for key, summary in operations["added"]],
    )
    section(
        f"Endpoints removed in {new_version}",
        [endpoint_line(key, summary) for key, summary in operations["removed"]],
    )

    body = []
    for (method, path), notes in operations["changed"]:
        body.append(f"- `{method}` `{path}`")
        body.extend(f"  - {note}" for note in notes)
    section("Endpoints changed", body)

    section(
        f"Models added in {new_version}",
        [f"- `{name}` ({count} properties)" for name, count in models["added"]],
    )
    section(
        f"Models removed in {new_version}",
        [f"- `{name}` ({count} properties)" for name, count in models["removed"]],
    )

    body = []
    for name, notes in models["changed"]:
        body.append(f"- `{name}`")
        body.extend(f"  - {note}" for note in notes)
    section("Models changed", body)

    return "\n".join(lines).rstrip() + "\n"


def render_index_markdown(specs: list[tuple[str, dict]], diffs: list[dict]) -> str:
    lines = [
        "# What changed, version by version",
        "",
        "Archived Oracle Essbase REST API specifications and the differences between",
        "them. Regenerate with `python3 spec/generate.py`; see",
        "[../README.md](../README.md) for where the specs come from.",
        "",
        "[coverage.md](coverage.md) turns this around and asks the other question:",
        "of everything the newest API offers, what does this client already reach?",
        "",
        "| Step | Endpoints | Models | Report |",
        "| --- | --- | --- | --- |",
    ]
    for diff in diffs:
        report = f"{diff['old']}-to-{diff['new']}.md"
        operations, models = diff["operations"], diff["models"]
        lines.append(
            f"| {diff['old']} to {diff['new']} "
            f"| {len(operations['added'])} added, {len(operations['removed'])} removed, "
            f"{len(operations['changed'])} changed "
            f"| {len(models['added'])} added, {len(models['removed'])} removed, "
            f"{len(models['changed'])} changed "
            f"| [{report}]({report}) |"
        )

    lines.extend(["", "## Endpoints added, by version", ""])
    for diff in diffs:
        lines.extend([f"### {diff['new']}", ""])
        added = diff["operations"]["added"]
        lines.extend(
            [endpoint_line(key, summary) for key, summary in added]
            if added
            else ["_No new endpoints._"]
        )
        lines.append("")

    lines.append(
        f"Endpoints present as of {specs[0][0]}, the oldest spec archived here, are not "
        "listed - there is nothing earlier to compare them against."
    )
    return "\n".join(lines).rstrip() + "\n"


def render_coverage_markdown(coverage: dict) -> str:
    counts = coverage["counts"]
    total = len(coverage["entries"])
    version = coverage["version"]

    lines = [
        f"# Client coverage of Essbase {version}",
        "",
        f"Every endpoint in the {version} specification, and whether this client reaches",
        "it. Generated by `spec/generate.py` - it reads the paths back out of the",
        "generated `client.api` classes and checks which of their methods the",
        "hand-written layer calls, so it measures the code rather than a kept list.",
        "",
        "| State | Count | Meaning |",
        "| --- | ---: | --- |",
    ]
    for state in ("wrapped", "generated", "not_generated"):
        lines.append(f"| {STATE_LABEL[state]} | {counts[state]} | {STATE_BLURB[state]} |")
    lines.extend([f"| **Total** | **{total}** | |", ""])

    by_state = {
        state: [entry for entry in coverage["entries"] if entry["state"] == state]
        for state in STATE_LABEL
    }

    lines.extend(
        [
            "## Not in the generated client",
            "",
            "These need a spec refresh before they can be wrapped: regenerate from a",
            "current specification (see `AGENTS.md`), then write the wrapper.",
            "",
        ]
    )
    for entry in by_state["not_generated"]:
        suffix = f" - {entry['summary']}" if entry["summary"] else ""
        lines.append(
            f"- `{entry['method']}` `{entry['path']}`{suffix} _(added {entry['added']})_"
        )

    lines.extend(
        [
            "",
            "## Generated, not exposed",
            "",
            "The generated method already exists for each of these, so exposing one is a",
            "matter of adding an `Ess*` wrapper - the cheapest place to add coverage.",
            "Grouped by the tag Oracle gives the endpoint.",
            "",
        ]
    )
    by_tag: dict[str, list[dict]] = {}
    for entry in by_state["generated"]:
        by_tag.setdefault(entry["tag"], []).append(entry)
    for tag in sorted(by_tag):
        lines.extend([f"<details><summary><strong>{tag}</strong> "
                      f"({len(by_tag[tag])})</summary>", ""])
        for entry in by_tag[tag]:
            methods = ", ".join(f"`{name}`" for name in entry["generated_methods"])
            lines.append(f"- `{entry['method']}` `{entry['path']}` - {methods}")
        lines.extend(["", "</details>", ""])

    lines.extend(["## Already exposed", "",
                  f"<details><summary>{counts['wrapped']} endpoints</summary>", ""])
    for entry in by_state["wrapped"]:
        methods = ", ".join(f"`{name}`" for name in entry["generated_methods"])
        via = f" - {methods}" if methods else " - hand-written HTTP"
        lines.append(f"- `{entry['method']}` `{entry['path']}`{via}")
    lines.extend(["", "</details>", ""])

    if coverage["stale"]:
        lines.extend(
            [
                "## Generated methods with no endpoint",
                "",
                f"The generated client still carries these, but Essbase {version} has no such",
                "endpoint - they went away between the spec this client was built from and",
                f"{version}. Calling one against a current server will fail.",
                "",
            ]
        )
        for method, path, names in coverage["stale"]:
            lines.append(
                f"- `{method}` `{path}` - " + ", ".join(f"`{name}`" for name in names)
            )
        lines.append("")

    lines.extend(
        [
            "## What this measurement misses",
            "",
            "Coverage is counted through the generated client, plus `NativeHttp` call",
            "sites whose path is a plain literal. "
            f"{coverage['unattributed']} `NativeHttp` call sites build their path from",
            "pieces at runtime and cannot be attributed to an endpoint, so the exposed",
            "count is a floor, not an exact figure.",
        ]
    )
    return "\n".join(lines).rstrip() + "\n"


